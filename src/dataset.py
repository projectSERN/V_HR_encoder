import os
from tqdm import tqdm
import numpy as np
import pandas as pd
import torch
from torch.utils.data import Dataset

from .config import config

class DFDC(Dataset):
    """
    Dataset class for the DFDC video samples' V_HR sequences (generated by pre-trained RhythmNet model) and labels.
    
    Attributes:
        split (str): Dataset split (train, val or test).
        video_paths (list of str): List of paths to the video samples.
        v_hr_seqs (list of torch.Tensor): V_HR sequences generated for the video samples.
        labels (list of int): List of labels for the video samples.
    """
    def __init__(self, split, v_hr_model):
        super().__init__()

        assert split in ['train', 'val', 'test'], f"Invalid split '{split}'"
        self.split = split
        self.video_paths, self.v_hr_seqs, self.labels = [], [], []
        v_hr_model.eval()                                                   # set RhythmNet model to eval mode (disable dropout, batchnorm, etc.)

        for subset_dir in os.listdir(config.DFDC_PATH):
            if subset_dir in ['subset_05', 'subset_06', 'subset_07']:
                metadata = pd.read_csv(os.path.join(config.DFDC_PATH, subset_dir, 'subset_metadata.csv'))
                for video_file in tqdm(os.listdir(os.path.join(config.DFDC_PATH, subset_dir, split)), desc=f"Generating/loading {subset_dir} {split} set's V_HR sequences"):
                    if video_file.endswith('.mp4'):
                        # extract label from metadata file
                        metadata_row = metadata[metadata['video'] == os.path.basename(video_file)]
                        assert len(metadata_row) == 1, f"Multiple or no metadata rows found for {video_file}"
                        label = 1 if metadata_row['label'].values[0] == 'FAKE' else 0

                        video_path = os.path.join(config.DFDC_PATH, subset_dir, split, video_file)
                        save_dir = os.path.join(os.path.dirname(video_path), "v_hr_seqs")
                        v_hr_save_path = os.path.join(save_dir, f"{os.path.basename(video_path).split('.')[0]}.npy")

                        # if V_HR sequence was not generated, generate it by passing it to the pre-trained RhythmNet model
                        if not os.path.exists(v_hr_save_path):
                            os.makedirs(save_dir, exist_ok=True)
                            with torch.no_grad():                           # no gradient calc. for inference
                                v_hr_seq = v_hr_model(video_path)
                            np.save(v_hr_save_path, v_hr_seq.cpu().numpy()) # save as numpy array, even if video is to be excluded
                        
                        # if V_HR sequence was already generated, load it and convert to tensor
                        else:
                            v_hr_seq = torch.from_numpy(np.load(v_hr_save_path, mmap_mode='r')).float()
                            
                        # video samples to be excluded are not added to the dataset
                        if v_hr_seq.shape[0] == 1 and v_hr_seq[0] == 0:
                            if config.VERBOSE:
                                print(f"{os.path.basename(video_path)}: no >=5s of continuous frames with detected face found, so is excluded")
                        else:
                            self.video_paths.append(video_path)
                            self.v_hr_seqs.append(v_hr_seq.unsqueeze(0))
                            self.labels.append(label)
                        
    def __len__(self):
        """ Returns the number of video samples in the dataset split. """
        return len(self.v_hr_seqs)

    def __getitem__(self, index):
        """ For the video sample at the given index, return its path, its V_HR sequence and its label.
        
        Args:
            index (int): Index of the video sample.
            
        Returns:
            video_path (str): Path to the video sample.
            v_hr_seq (torch.Tensor): V_HR sequence for the video sample, shape: (1, num_clips).
            label (int): Scalar label of the video sample, i.e., 0 if video is real, 1 if fake.
        """
        video_path = self.video_paths[index]
        v_hr_seq = self.v_hr_seqs[index]
        label = self.labels[index]

        return video_path, v_hr_seq, label

def collate_fn(batch):
    """ Custom collate function for the DataLoader, to handle potentially variable length V_HR sequences.
    
    Args:
        batch (list of tuples): List of tuples, where each tuple contains a video sample's path, its V_HR sequence and its label.
        
    Returns:
        batch (dict of str: torch.Tensor): Batched paths', V_HR sequences' and labels' tensors of all video samples in the batch.
    
    """
    # handle variable length V_HR sequences by padding
    # ideally, num_clips should be 15
    seq_lens = [item[1].shape[1] for item in batch]
    if len(set(seq_lens)) == 1:
        v_hr_seq = torch.stack([item[1] for item in batch], dim=0)      # 3d tensor of floats, shape: (batch_size, 1, num_clips)
    else:
        v_hr_seq = torch.zeros(len(batch), 1, max(seq_lens))
        for i, item in enumerate(batch):
            v_hr_seq[i, :, :item[1].shape[1]] = item[1]
    
    video_path = [item[0] for item in batch]                            # list of str, length: batch_size
    label = torch.tensor([item[2] for item in batch]).float()           # 1d tensor of floats, shape: (batch_size,)

    v_hr_seq = v_hr_seq.to(config.DEVICE)
    label = label.to(config.DEVICE)
    
    batch = {'video_path': video_path, 'V_HR': v_hr_seq, 'label': label}
    return batch